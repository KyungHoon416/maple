#!/usr/bin/env node
/* Builds the static rarity index from all 4,096 answer combinations (equal-weight QA space,
 * NOT a real-user or gacha probability). Output: src/rarity-index.js, docs/RARITY_DISTRIBUTION.csv */
'use strict';
const fs = require('fs');
const path = require('path');
const D = require('../src/data.js');
const E = require('../src/engine.js');

const eng = E.create(D, null);
const T = D.CONFIG.rarityThresholds;
const grade = c => (c >= T.N ? 'N' : c >= T.R ? 'R' : c >= T.SR ? 'SR' : 'SSR');

const counts = {};
let noCard = 0;
for (const a of E.allAnswers()) {
  const r = eng.match(a);
  if (!r.primary) { noCard++; continue; }
  const k = r.primary.signatureKey;
  counts[k] = (counts[k] || 0) + 1;
}
const keys = {};
Object.keys(counts).sort().forEach(k => { keys[k] = { patternCount: counts[k], rarity: grade(counts[k]) }; });
const index = { dataVersion: D.DATA_VERSION, rarityRuleVersion: D.CONFIG.rarityRuleVersion, thresholds: T, space: 4096, noCard, keys };

const root = path.join(__dirname, '..');
fs.writeFileSync(path.join(root, 'src/rarity-index.js'),
  '/* GENERATED by scripts/generate-rarity.js — do not edit. */\n' +
  '(function(r){var x=' + JSON.stringify(index) + ';if(typeof module!=="undefined"&&module.exports)module.exports=x;else r.MFS_RARITY=x;})(typeof window!=="undefined"?window:globalThis);\n');

const rows = [['signatureKey', 'skillId', 'skillLabel', 'secondaryFamily', 'context', 'patternCount', 'rarity']];
Object.entries(keys).sort((a, b) => b[1].patternCount - a[1].patternCount).forEach(([k, v]) => {
  const [sk, fam, ctx] = k.split('|');
  rows.push([k, sk, D.SKILL_BY_ID[sk].label, fam, ctx, v.patternCount, v.rarity]);
});
fs.writeFileSync(path.join(root, 'docs/RARITY_DISTRIBUTION.csv'), '﻿' + rows.map(r => r.map(c => '"' + String(c).replace(/"/g, '""') + '"').join(',')).join('\n') + '\n');

const g = { N: 0, R: 0, SR: 0, SSR: 0 }, gk = { N: 0, R: 0, SR: 0, SSR: 0 };
Object.values(keys).forEach(v => { g[v.rarity] += v.patternCount; gk[v.rarity]++; });
console.log('rarity index written:', Object.keys(keys).length, 'signature keys; no-card combos:', noCard);
console.log('combos by grade', g, 'keys by grade', gk);
const missing = Object.entries(gk).filter(([, n]) => n === 0).map(([k]) => k);
if (missing.length) { console.error('WARNING: grades with no signature key:', missing.join(',')); process.exitCode = 1; }
